#!/usr/bin/env python3
"""Generate the plugin part of a deploy bundle from backend/plugins/<code>/.

Every plugin is a folder with plugin-manifest.json + deploy.json; nothing else in the pipeline
names a plugin. Adding a plugin = adding its folder (AGENTS.md §2.6: own process, own database).

    gen-plugins.py <repo-root> <bundle-dir>

Writes into <bundle-dir>:
    compose.plugins.yml               one service per plugin (+ its DB password on postgres)
    compose.plugins.stage-limits.yml  staging caps for those services (used only via FSP_OVERLAYS)
    plugins.env                       FSP_PLUGINS="kyc inventory" (+ per-plugin metadata)
    plugins/<code>.manifest.json      the manifest exactly as committed (drift check input)
    plugins/<code>.deploy.json
"""
import json
import pathlib
import re
import shutil
import sys

CODE_RE = re.compile(r"^[a-z][a-z0-9]{1,30}$")
MEM_RE = re.compile(r"^[0-9]+m$")


def die(msg: str) -> None:
    print(f"gen-plugins: {msg}", file=sys.stderr)
    sys.exit(1)


def load_plugins(root: pathlib.Path) -> list[dict]:
    plugins, ports = [], {}
    for manifest_path in sorted(root.glob("backend/plugins/*/plugin-manifest.json")):
        folder = manifest_path.parent
        code = folder.name
        manifest = json.loads(manifest_path.read_text())
        if manifest.get("code") != code:
            die(f"{manifest_path}: code '{manifest.get('code')}' must equal its folder name '{code}'")
        if not CODE_RE.match(code):
            die(f"plugin code '{code}' must match {CODE_RE.pattern}")
        deploy_path = folder / "deploy.json"
        if not deploy_path.is_file():
            die(f"{folder}: missing deploy.json (port, secrets, staging caps)")
        deploy = json.loads(deploy_path.read_text())
        port = deploy.get("port")
        if not isinstance(port, int) or not 1024 < port < 65535:
            die(f"{deploy_path}: port must be an integer 1025-65534")
        if port in ports:
            die(f"{deploy_path}: port {port} already used by plugin '{ports[port]}'")
        ports[port] = code
        secrets = deploy.get("secrets", [])
        upper = code.upper()
        for s in secrets:
            if not re.match(rf"^FSP_PLUGIN_{upper}_[A-Z0-9_]+$", s):
                die(f"{deploy_path}: secret '{s}' must be named FSP_PLUGIN_{upper}_*")
        stage = deploy.get("staging", {})
        mem, heap = stage.get("mem", "384m"), stage.get("heap", "160m")
        if not (MEM_RE.match(mem) and MEM_RE.match(heap)):
            die(f"{deploy_path}: staging mem/heap must look like '384m'")
        plugins.append({
            "code": code, "upper": upper, "port": port, "secrets": secrets,
            "cpus": float(stage.get("cpus", 0.25)), "mem": mem, "heap": heap,
            "version": manifest.get("version", ""), "manifest_path": manifest_path,
            "deploy_path": deploy_path,
        })
    if not plugins:
        die("no plugins found under backend/plugins/*/plugin-manifest.json")
    return plugins


def compose_plugins(plugins: list[dict]) -> str:
    out = ["# GENERATED by deploy/pipeline/scripts/gen-plugins.py from backend/plugins/*/ — do not edit.",
           "services:", "  postgres:", "    environment:"]
    for p in plugins:
        out.append(f"      FSP_PLUGIN_{p['upper']}_DB_PASSWORD: ${{FSP_PLUGIN_{p['upper']}_DB_PASSWORD:-}}")
    for p in plugins:
        c, u = p["code"], p["upper"]
        out += [
            f"  plugin-{c}:",
            f"    image: ${{FSP_IMAGE_{u}:?release.env must pin {c}}}",
            f"    container_name: ${{FSP_PREFIX}}-plugin-{c}",
            "    restart: unless-stopped",
            "    labels:",
            f"      com.afriqpay.fsp.plugin: {c}",
            "    environment:",
            f"      FSP_PLUGIN_{u}_DB_URL: jdbc:postgresql://postgres:5432/fsp_plugin_{c}",
            f"      FSP_PLUGIN_{u}_DB_USER: fsp_plugin_{c}",
            f"      FSP_PLUGIN_{u}_DB_PASSWORD: ${{FSP_PLUGIN_{u}_DB_PASSWORD:?}}",
            f"      SERVER_PORT: \"{p['port']}\"",
            "      FSP_GATEWAY_URL: http://gateway:8090",
            "      FSP_IDP_ISSUER: https://${FSP_AUTH_HOST}",
            f"      FSP_PLUGIN_{u}_CLIENT_KEY: /opt/fsp/pki/plugin-{c}-client.pem",
            f"      FSP_PLUGIN_{u}_DPOP_KEY: /opt/fsp/pki/plugin-{c}-dpop.pem",
            f"      FSP_PLUGIN_{u}_CREATE_KEYS: \"false\"",
        ]
        out += [f"      {s}: ${{{s}:?}}" for s in p["secrets"]]
        out += [
            "    volumes:",
            "      - ${FSP_CONF_DIR}/pki:/opt/fsp/pki:ro",
            "    networks: [fsp]",
            "    depends_on:",
            "      postgres: { condition: service_healthy }",
            "    logging:",
            "      driver: json-file",
            "      options: { max-size: \"${FSP_LOG_MAX_SIZE:-10m}\", max-file: \"${FSP_LOG_MAX_FILES:-3}\" }",
            "    healthcheck:",
            f"      test: [\"CMD-SHELL\", \"nc -z 127.0.0.1 {p['port']} || exit 1\"]",
            "      interval: 10s",
            "      timeout: 5s",
            "      retries: 60",
            "      start_period: 30s",
        ]
    return "\n".join(out) + "\n"


def compose_stage_limits(plugins: list[dict]) -> str:
    # Same small-JVM profile as compose.stage-limits.yml (idp/gateway/bff); heap/mem/cpus per plugin.
    out = ["# GENERATED by deploy/pipeline/scripts/gen-plugins.py — staging caps for plugins (see compose.stage-limits.yml).",
           "services:"]
    for p in plugins:
        out += [
            f"  plugin-{p['code']}:",
            "    cgroup_parent: ${FSP_SLICE:?}",
            "    cpu_shares: 128",
            "    oom_score_adj: 500",
            "    pids_limit: 256",
            f"    cpus: {p['cpus']}",
            f"    mem_limit: {p['mem']}",
            f"    memswap_limit: {p['mem']}",
            "    entrypoint: [\"java\", \"-XX:+UseSerialGC\", \"-Xms32m\", \"-Xmx" + p["heap"] + "\", \"-XX:TieredStopAtLevel=1\",",
            "                 \"-XX:ReservedCodeCacheSize=48m\", \"-XX:ActiveProcessorCount=1\",",
            "                 \"-XX:+ExitOnOutOfMemoryError\", \"-jar\", \"/app/app.jar\"]",
            "    environment:",
            "      SERVER_TOMCAT_THREADS_MAX: \"16\"",
            "      SERVER_TOMCAT_THREADS_MIN_SPARE: \"2\"",
            "      SPRING_DATASOURCE_HIKARI_MAXIMUM_POOL_SIZE: \"3\"",
            "      SPRING_DATASOURCE_HIKARI_MINIMUM_IDLE: \"1\"",
        ]
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 3:
        die("usage: gen-plugins.py <repo-root> <bundle-dir>")
    root, bundle = pathlib.Path(sys.argv[1]).resolve(), pathlib.Path(sys.argv[2])
    plugins = load_plugins(root)
    (bundle / "plugins").mkdir(parents=True, exist_ok=True)
    (bundle / "compose.plugins.yml").write_text(compose_plugins(plugins))
    (bundle / "compose.plugins.stage-limits.yml").write_text(compose_stage_limits(plugins))
    env = [f'FSP_PLUGINS="{" ".join(p["code"] for p in plugins)}"']
    for p in plugins:
        env.append(f'FSP_PLUGIN_{p["upper"]}_PORT={p["port"]}')
        env.append(f'FSP_PLUGIN_{p["upper"]}_SECRETS="{" ".join(p["secrets"])}"')
    (bundle / "plugins.env").write_text("# GENERATED by gen-plugins.py\n" + "\n".join(env) + "\n")
    for p in plugins:
        shutil.copyfile(p["manifest_path"], bundle / "plugins" / f"{p['code']}.manifest.json")
        shutil.copyfile(p["deploy_path"], bundle / "plugins" / f"{p['code']}.deploy.json")
    print("plugins: " + ", ".join(f"{p['code']}@{p['version']}:{p['port']}" for p in plugins))


if __name__ == "__main__":
    main()
